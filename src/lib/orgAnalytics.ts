export interface OrgSummary {
  opportunities: number;
  registrations: number;
  attended: number;
  no_show_rate: number;
  verified_hours: number;
  unique_volunteers: number;
  repeat_volunteers: number;
  avg_fill_rate: number;
}

export interface WeekPoint {
  week_start: string;
  registrations: number;
  attended: number;
  hours: number;
}

export interface OpportunityRow {
  opportunity_id: string;
  title: string;
  date: string;
  category: string | null;
  max_volunteers: number | null;
  registered: number;
  attended: number;
  hours: number;
  fill_rate: number;
}

export interface DateRange {
  from: string; // YYYY-MM-DD
  to: string;
}

const DAY = 86_400_000;

export function toISODate(d: Date): string {
  return d.toISOString().slice(0, 10);
}

export function rangeForDays(days: number, now: Date = new Date()): DateRange {
  return { from: toISODate(new Date(now.getTime() - days * DAY)), to: toISODate(now) };
}

export function fillRate(registered: number, capacity: number | null | undefined): number {
  if (!capacity || capacity <= 0 || registered <= 0) return 0;
  return Math.min(registered / capacity, 1);
}

/** Share of registrations that did not attend (0..1). */
export function noShowRate(registered: number, attended: number): number {
  if (registered <= 0) return 0;
  return Math.min(Math.max((registered - attended) / registered, 0), 1);
}

function mondayOf(iso: string): Date {
  const d = new Date(`${iso}T00:00:00Z`);
  const dow = (d.getUTCDay() + 6) % 7;
  return new Date(d.getTime() - dow * DAY);
}

/** Return one point per ISO week between from and to, zero-filling missing weeks. */
export function fillMissingWeeks(points: WeekPoint[], range: DateRange): WeekPoint[] {
  const byWeek = new Map(points.map((p) => [p.week_start.slice(0, 10), p]));
  const out: WeekPoint[] = [];
  const end = new Date(`${range.to}T00:00:00Z`).getTime();
  for (let t = mondayOf(range.from).getTime(); t <= end && out.length < 160; t += 7 * DAY) {
    const key = toISODate(new Date(t));
    out.push(byWeek.get(key) ?? { week_start: key, registrations: 0, attended: 0, hours: 0 });
  }
  return out;
}

export interface Trend {
  direction: "up" | "down" | "flat";
  changePct: number | null;
}

/** Compare the second half of a series against the first half. */
export function summarizeTrend(values: number[]): Trend {
  if (values.length < 2) return { direction: "flat", changePct: null };
  const mid = Math.floor(values.length / 2);
  const sum = (a: number[]) => a.reduce((x, y) => x + y, 0);
  const first = sum(values.slice(0, mid));
  const second = sum(values.slice(values.length - mid));
  if (first === 0) return { direction: second > 0 ? "up" : "flat", changePct: null };
  const pct = ((second - first) / first) * 100;
  if (Math.abs(pct) < 1) return { direction: "flat", changePct: 0 };
  return { direction: pct > 0 ? "up" : "down", changePct: Math.round(pct) };
}

export function formatHours(hours: number | null | undefined): string {
  const h = Number(hours ?? 0);
  if (!Number.isFinite(h) || h <= 0) return "0 h";
  if (h < 10) return `${Math.round(h * 10) / 10} h`;
  return `${Math.round(h).toLocaleString("en-IN")} h`;
}

export function formatPct(ratio: number | null | undefined): string {
  return `${Math.round((Number(ratio) || 0) * 100)}%`;
}

export function buildImpactReport(summary: OrgSummary, orgName: string, range: DateRange): string {
  const lines = [
    `Impact Report: ${orgName}`,
    `Period: ${range.from} to ${range.to}`,
    "",
    `- Volunteering opportunities run: ${summary.opportunities}`,
    `- Volunteer registrations: ${summary.registrations}`,
    `- Volunteers who attended: ${summary.attended}`,
    `- Verified volunteer hours: ${formatHours(summary.verified_hours)}`,
    `- Unique volunteers engaged: ${summary.unique_volunteers}`,
    `- Returning volunteers (joined 2+ opportunities): ${summary.repeat_volunteers}`,
    `- Average capacity filled: ${formatPct(summary.avg_fill_rate)}`,
    `- No-show rate (past events): ${formatPct(summary.no_show_rate)}`,
    "",
    "Generated by SocioSquad.",
  ];
  return lines.join("\n");
}
